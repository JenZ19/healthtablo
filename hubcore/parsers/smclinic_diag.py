"""Парсер протоколов инструментальных исследований ГК «СМ-Клиника».

Это не бланк анализов, а описательный протокол: УЗИ, КТ, рентген, ФГДС.
Ни таблицы показателей, ни ФИО, ни даты внутри файла нет — только текст
описания и заключение:

    Описание приема
    Ультразвуковое исследование щитовидной железы
    ...
    Размеры:
    Правая доля: 45х15х20 мм. Объем – 7 см3
    Заключение: УЗ признаки диффузных изменений

Важное: generic-парсер на таком тексте выдумывает «показатели» из строк
с размерами («Правая доля: 45х15х20 мм» → якобы результат 45). Поэтому
протокол опознаётся отдельно и НЕ отдаёт ни одного результата — он
сохраняется как документ с полным текстом, доступным поиску, а дата и
модальность проставляются извне, из списка кабинета.
"""

from __future__ import annotations

import re

from .base import BaseParser, ParsedDocument

LAB_NAME = "СМ-Клиника, инструментальные исследования"

# Характерные маркеры протокола
_MARKERS = (
    "описание приема",
    "протокол ультразвукового исследования",
    "ультразвуковое исследование",
    "заключение:",
    "эхо-признаки",
    "эхопризнаки",
    "компьютерная томография",
    "рентгенография",
    "эзофагогастродуоденоскопия",
)

# Признак того, что это всё-таки бланк анализов, а не протокол
_LAB_MARKERS = ("показатель", "референсные пределы", "ед. изм.", "биоматериал:")

MODALITIES = [
    ("компьютерн", "КТ"),
    ("эзофагогастродуоден", "ФГДС"),
    ("гастроскоп", "ФГДС"),
    ("колоноскоп", "Колоноскопия"),
    ("эндоскоп", "Эндоскопия"),
    ("рентген", "Рентген"),
    ("маммограф", "Маммография"),
    ("ультразвук", "УЗИ"),
    ("узи", "УЗИ"),
    ("эхо", "УЗИ"),
]

ORGANS = [
    ("щитовидн", "щитовидной железы"),
    ("молочны", "молочных желёз"),
    ("малого таза", "органов малого таза"),
    ("матк", "матки"),
    ("брюшной полости", "органов брюшной полости"),
    ("почек", "почек"),
    ("печен", "печени"),
    ("лимфат", "лимфатических узлов"),
    ("позвоночник", "позвоночника"),
    ("сустав", "суставов"),
    ("грудной клетк", "грудной клетки"),
    ("лёгких", "лёгких"),
    ("легких", "лёгких"),
    ("придаточных пазух", "придаточных пазух носа"),
    ("мочевого пузыр", "мочевого пузыря"),
    ("вен ", "вен"),
    ("артерий", "артерий"),
]


def describe(text: str) -> str:
    """Собрать человекочитаемое название протокола: «УЗИ щитовидной железы»."""
    low = text.lower()
    mod = next((v for k, v in MODALITIES if k in low), "Исследование")
    organ = next((v for k, v in ORGANS if k in low), "")
    return f"{mod} {organ}".strip()


def conclusion(text: str) -> str | None:
    """Вытащить заключение — самое ценное в протоколе."""
    m = re.search(r"Заключение\s*:?\s*(.+)", text, re.I | re.S)
    if not m:
        return None
    tail = re.sub(r"\s+", " ", m.group(1)).strip()
    return tail[:400] or None


class SmClinicDiagParser(BaseParser):
    name = "smclinic_diag"

    def can_parse(self, text: str) -> bool:
        low = text.lower()
        if any(k in low for k in _LAB_MARKERS):
            return False
        return any(k in low for k in _MARKERS)

    def parse(self, text: str) -> ParsedDocument:
        doc = ParsedDocument(lab_name=LAB_NAME)
        doc.results = []  # протокол намеренно не даёт числовых результатов
        doc.parsed_ok = True
        concl = conclusion(text)
        doc.parse_note = describe(text) + (f" — {concl[:160]}" if concl else "")
        return doc
